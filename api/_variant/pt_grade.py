def grade_of(label):
    """'중3 2학기 1단원 (삼각비)' → '중3'  (못 알아보면 None)"""
    import re
    m = re.search(r'(중\s*[123])', str(label or ''))
    if m:
        return m.group(1).replace(' ', '')
    m = re.search(r'([123])\s*학년', str(label or ''))
    return ('중' + m.group(1)) if m else None


def block(grade):
    """생성·재작성 프롬프트에 그대로 끼워 넣을 한 덩이."""
    g = grade if grade in TOOLS else grade_of(grade)
    if g not in TOOLS:
        return ''
    return ("""
이 교재는 **%s 학생**이 푼다. 문제도 해설도 %s 이 배운 것만으로 풀려야 한다.

%s 이(가) 쓸 수 있는 것
%s

쓰면 안 되는 것 (아직 안 배웠다)
  %s

⚠ 답이 맞아도 %s 이 못 읽는 해설이면 못 쓴다.
  직각삼각형이 아니면 **수선을 그어** 나누고, 각을 만들려면 **보조선을 그어라.**
  (실측: 'tan70°를 a로' 같은 문제도 보조선 하나로 %s 범위에서 풀린다)
""" % (g, g, g, TOOLS[g], BANNED[g], g, g))


