-- 학년 승급을 종류별(학년+1 · 예비중 · 예비고 · 졸업)로 골라 실행 (2026-10-23)
-- 1) 실행 기록을 '연도' 단위에서 '실행 1건(id)' 단위로 — 같은 해에 종류를 나눠 여러 번 실행 가능
-- 2) promote_grades 에 p_kinds text[] 추가 (NULL = 전부, pg_cron 의 promote_grades(null,false) 는 그대로 전부)
-- 3) 같은 해에 이미 끝난 종류는 다시 못 돌린다(되돌리지 않은 기록 기준)
-- 4) undo_grade_promotion(p_run_id) — 실행 1건 단위 되돌리기

-- ── 1. 실행 기록 표 ──────────────────────────────────────────────
alter table public.grade_promotion_runs add column if not exists id bigint generated by default as identity;
alter table public.grade_promotion_runs add column if not exists kinds text[] not null default array['학년+1','예비중','예비고','졸업'];
do $$
declare r record;
begin
  for r in select conname from pg_constraint where conrelid = 'public.grade_promotion_runs'::regclass and contype = 'p' loop
    execute format('alter table public.grade_promotion_runs drop constraint %I', r.conname);
  end loop;
end $$;
alter table public.grade_promotion_runs add primary key (id);
create index if not exists grade_promotion_runs_year_idx on public.grade_promotion_runs (run_year);

-- ── 2. 승급 함수 ─────────────────────────────────────────────────
drop function if exists public.promote_grades(integer, boolean);
create or replace function public.promote_grades(p_year integer default null, p_dry_run boolean default true, p_kinds text[] default null)
returns jsonb
language plpgsql
as $function$
declare
  v_year   int  := coalesce(p_year, extract(year from (now() at time zone 'Asia/Seoul'))::int);
  v_today  date := (now() at time zone 'Asia/Seoul')::date;
  v_all    text[] := array['학년+1','예비중','예비고','졸업'];
  v_kinds  text[] := coalesce(p_kinds, v_all);
  v_done_kinds text[];      -- 이 해에 이미 끝난(되돌리지 않은) 종류들
  v_overlap    text[];      -- 이번에 요청한 종류 중 이미 끝난 것
  v_total  int;
  v_snap   jsonb;
  v_plan   jsonb;
  v_skip   jsonb;
  v_run_id bigint;
begin
  if array_length(v_kinds, 1) is null then
    return jsonb_build_object('ok', false, 'year', v_year, 'error', '실행할 종류를 하나 이상 고르세요.');
  end if;

  -- 이 해에 이미 끝난 종류 (되돌린 기록은 제외)
  select coalesce(array_agg(distinct k), '{}') into v_done_kinds
    from grade_promotion_runs r, unnest(r.kinds) k
   where r.run_year = v_year and r.undone_at is null;
  select coalesce(array_agg(k), '{}') into v_overlap
    from unnest(v_kinds) k where k = any(v_done_kinds);

  drop table if exists _plan;
  create temp table _plan on commit drop as
  with target as (
    select u.id, u.name, u.school, u.grade, u.school_level, u.student_code, u.graduated_at,
           case
             when u.school ~ '(고등학교|고)$' then 'high'
             when u.school ~ '(중학교|중)$'   then 'middle'
             when u.school ~ '(초등학교|초)$' then 'elem'
           end                                              as lv,
           nullif(substring(u.grade from '[0-9]+'), '')::int as g
      from users u
     where u.role = 'student'
       and u.status = 'active'
       and u.reading_room_yn is not true
       and (u.reading_room_class is null or btrim(u.reading_room_class) = '')
       and u.graduated_at is null
  ), plan0 as (
  select t.id, t.name, t.student_code,
         t.school       as old_school,
         t.grade        as old_grade,
         t.school_level as old_level,
         t.graduated_at as old_grad,
         t.lv, t.g,
         case when t.lv = 'elem'   and t.g = 6 then '예비중'
              when t.lv = 'middle' and t.g = 3 then '예비고'
              else t.school end                             as new_school,
         case when t.lv = 'high'   and t.g = 3 then t.grade
              when t.lv = 'elem'   and t.g = 6 then '1학년'
              when t.lv = 'middle' and t.g = 3 then '1학년'
              else (t.g + 1)::text || '학년' end             as new_grade,
         case when t.lv = 'elem'   and t.g = 6
                then case when t.school_level in ('middle','high','both')
                          then t.school_level else 'middle' end
              when t.lv = 'middle' and t.g = 3
                then case when t.school_level in ('high','both')
                          then t.school_level else 'high' end
              else t.school_level end                       as new_level,
         case when t.lv = 'high' and t.g = 3 then v_today end as new_grad,
         case when t.lv = 'elem'   and t.g = 6 then '예비중'
              when t.lv = 'middle' and t.g = 3 then '예비고'
              when t.lv = 'high'   and t.g = 3 then '졸업'
              else '학년+1' end                              as kind
    from target t
   where t.lv is not null
     and t.g is not null
     and ((t.lv = 'elem'   and t.g between 1 and 6)
       or (t.lv = 'middle' and t.g between 1 and 3)
       or (t.lv = 'high'   and t.g between 1 and 3))
  )
  select * from plan0 where kind = any(v_kinds);          -- 고른 종류만

  -- 판정하지 못해 건너뛴 학생 (종류 선택과 무관하게 전체 기준)
  select coalesce(jsonb_agg(jsonb_build_object(
           'id', u.id, 'name', u.name, 'school', u.school,
           'grade', u.grade, 'school_level', u.school_level,
           'why', case
             when u.school is null or btrim(u.school) = ''                then '학교명 없음'
             when u.school !~ '(고등학교|고|중학교|중|초등학교|초)$'        then '학교명으로 학교급을 못 읽음'
             when nullif(substring(u.grade from '[0-9]+'), '') is null     then '학년 숫자 없음'
             else '학년이 범위 밖' end)), '[]'::jsonb)
    into v_skip
    from users u
   where u.role = 'student' and u.status = 'active'
     and u.reading_room_yn is not true
     and (u.reading_room_class is null or btrim(u.reading_room_class) = '')
     and u.graduated_at is null
     and (u.school is null or btrim(u.school) = ''
          or u.school !~ '(고등학교|고|중학교|중|초등학교|초)$'
          or nullif(substring(u.grade from '[0-9]+'), '') is null
          or not ((u.school ~ '(초등학교|초)$' and nullif(substring(u.grade from '[0-9]+'), '')::int between 1 and 6)
               or (u.school ~ '(중학교|중)$'   and nullif(substring(u.grade from '[0-9]+'), '')::int between 1 and 3)
               or (u.school ~ '(고등학교|고)$' and nullif(substring(u.grade from '[0-9]+'), '')::int between 1 and 3)));

  select count(*) into v_total from _plan;

  select coalesce(jsonb_agg(jsonb_build_object(
           'id', p.id, 'name', p.name, 'code', p.student_code, 'kind', p.kind,
           'from', p.old_school || ' ' || p.old_grade,
           'to',   p.new_school || ' ' || p.new_grade
             || case when p.new_grad is not null then ' (졸업)' else '' end,
           'level_from', p.old_level, 'level_to', p.new_level)
           order by p.kind, p.old_school, p.name), '[]'::jsonb)
    into v_plan from _plan p;

  if p_dry_run then
    return jsonb_build_object(
      'ok', true, 'dry_run', true, 'year', v_year, 'today', v_today,
      'kinds', to_jsonb(v_kinds),
      'done_kinds', to_jsonb(v_done_kinds),
      'already_done', (array_length(v_overlap, 1) is not null),
      'overlap_kinds', to_jsonb(v_overlap),
      'total', v_total, 'changes', v_plan, 'skipped', v_skip);
  end if;

  if array_length(v_overlap, 1) is not null then
    return jsonb_build_object('ok', false, 'year', v_year,
      'error', v_year || '년 ' || array_to_string(v_overlap, '·') || ' 승급은 이미 끝났습니다. 되돌린 뒤 다시 실행하세요.');
  end if;
  if v_total = 0 then
    return jsonb_build_object('ok', false, 'year', v_year, 'error', '고른 종류에 해당하는 학생이 없습니다.');
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
           'id', p.id, 'school', p.old_school, 'grade', p.old_grade,
           'school_level', p.old_level, 'graduated_at', p.old_grad)), '[]'::jsonb)
    into v_snap from _plan p;

  insert into grade_promotion_runs(run_year, total, snapshot, kinds)
  values (v_year, v_total, v_snap, v_kinds)
  returning id into v_run_id;

  update users u
     set school       = p.new_school,
         grade        = p.new_grade,
         school_level = p.new_level,
         graduated_at = p.new_grad
    from _plan p
   where u.id = p.id;

  return jsonb_build_object('ok', true, 'dry_run', false, 'year', v_year, 'run_id', v_run_id,
    'kinds', to_jsonb(v_kinds), 'total', v_total, 'changes', v_plan, 'skipped', v_skip);
end $function$;

-- ── 3. 되돌리기: 실행 1건(id) 단위 ─────────────────────────────────
drop function if exists public.undo_grade_promotion(integer);
create or replace function public.undo_grade_promotion(p_run_id bigint)
returns jsonb
language plpgsql
as $function$
declare
  v_run grade_promotion_runs%rowtype;
  v_n   int;
begin
  select * into v_run from grade_promotion_runs where id = p_run_id;
  if v_run.id is null then
    return jsonb_build_object('ok', false, 'error', '실행 기록을 찾지 못했습니다.');
  end if;
  if v_run.undone_at is not null then
    return jsonb_build_object('ok', false, 'error', '이미 되돌린 기록입니다.');
  end if;

  update users u
     set school       = s.school,
         grade        = s.grade,
         school_level = s.school_level,
         graduated_at = s.graduated_at
    from (
      select (e->>'id')::uuid as id, e->>'school' as school, e->>'grade' as grade,
             e->>'school_level' as school_level, (e->>'graduated_at')::date as graduated_at
        from jsonb_array_elements(v_run.snapshot) e
    ) s
   where u.id = s.id;
  get diagnostics v_n = row_count;

  update grade_promotion_runs set undone_at = now() where id = p_run_id;
  return jsonb_build_object('ok', true, 'run_id', p_run_id, 'year', v_run.run_year,
    'kinds', to_jsonb(v_run.kinds), 'restored', v_n);
end $function$;

-- 확인
select id, run_year, kinds, total, run_at, undone_at from public.grade_promotion_runs order by id;
